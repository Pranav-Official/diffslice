import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const run = promisify(execFile);
const project = path.resolve(import.meta.dirname, '..');
const source = path.resolve(process.argv[2] ?? path.join(project, '../Dev-Chestrav'));
const output = path.join(project, '.artifacts', 'precommit', String(Date.now()));
const repo = path.join(output, 'repo');
await mkdir(output, { recursive: true });
await run('git', ['clone', '--shared', '--quiet', source, repo], { windowsHide: true });
const git = (...args) => run('git', ['-C', repo, ...args], { windowsHide: true, timeout: 600_000, maxBuffer: 32 * 1024 * 1024 });
const cli = (...args) => run(process.execPath, [path.join(project, 'dist/cli.js'), ...args, '--repo', repo, '--json'], { windowsHide: true, timeout: 600_000, maxBuffer: 32 * 1024 * 1024 });
await git('config', 'user.name', 'DiffSlice verification'); await git('config', 'user.email', 'diffslice@example.invalid'); await git('config', 'core.autocrlf', 'false');
console.log('Installing private Graphify runtime and combined hook in the DevChestra clone...');
const setupStart = performance.now();
const installed = JSON.parse((await cli('init', '--install-hook')).stdout);
const setupMs = Math.round(performance.now() - setupStart);
assert.equal(installed.hook.status, 'installed');
assert.equal(installed.hook.sql, true);
const probe = 'packages/engine/src/diffslice-hook-probe.ts';
await writeFile(path.join(repo, probe), 'export function diffsliceStagedProbe() { return 1; }\n');
await git('add', 'diffslice.modules.json', probe);
const tree = (await git('write-tree')).stdout.trim();
await writeFile(path.join(repo, probe), 'export function diffsliceUnstagedProbe() { return 2; }\n');
console.log('Committing staged probe; full Graphify graph and DiffSlice cache must finish first...');
const commitStart = performance.now();
const commit = await git('commit', '-m', 'Verify combined staged Graphify and DiffSlice update');
const commitMs = Math.round(performance.now() - commitStart);
await writeFile(path.join(output, 'commit.log'), commit.stdout + commit.stderr);
const ready = JSON.parse(await readFile(path.join(repo, '.git/diffslice/precommit-ready.json'), 'utf8'));
assert.equal(ready.tree, tree); assert.equal((await git('rev-parse', 'HEAD^{tree}')).stdout.trim(), tree);
const graph = JSON.parse(await readFile(ready.graphPath, 'utf8'));
const labels = graph.nodes.map(node => node.label ?? '').join('\n');
assert.match(labels, /\bdiffsliceStagedProbe\b/); assert.doesNotMatch(labels, /\bdiffsliceUnstagedProbe\b/);
assert.match(await readFile(path.join(repo, probe), 'utf8'), /diffsliceUnstagedProbe/);
assert.equal(JSON.parse(await readFile(path.join(repo, '.git/diffslice/modules-index-v1.json'), 'utf8')).tree, tree);
const warmStart = performance.now(); const warm = JSON.parse((await cli('hook', 'run')).stdout); const warmMs = Math.round(performance.now() - warmStart);
assert.equal(warm.cached, true);
console.log('Committing a one-file topology change, with unstaged and untracked sentinels...');
await writeFile(path.join(repo, probe), 'export function diffsliceStagedProbe() { return 2; }\nexport function diffsliceIncrementalProbe() { return diffsliceStagedProbe(); }\n');
await git('add', probe);
const incrementalTree = (await git('write-tree')).stdout.trim();
await writeFile(path.join(repo, probe), 'export function diffsliceUnstagedProbe() { return 999; }\n');
await writeFile(path.join(repo, 'diffslice-untracked-probe.ts'), 'export function diffsliceUntrackedProbe() {}\n');
const incrementalStart = performance.now();
const incrementalCommit = await git('commit', '-m', 'Verify one-file incremental combined update');
const incrementalMs = Math.round(performance.now() - incrementalStart);
await writeFile(path.join(output, 'incremental.log'), incrementalCommit.stdout + incrementalCommit.stderr);
const incrementalReady = JSON.parse(await readFile(path.join(repo, '.git/diffslice/precommit-ready.json'), 'utf8'));
assert.equal(incrementalReady.tree, incrementalTree);
assert.equal((await git('rev-parse', 'HEAD^{tree}')).stdout.trim(), incrementalTree);
assert.equal(incrementalReady.materialized.written, 1);
assert.equal(incrementalReady.measuredBlobs, 1);
const incrementalGraph = JSON.parse(await readFile(incrementalReady.graphPath, 'utf8'));
const incrementalLabels = incrementalGraph.nodes.map(node => node.label ?? '').join('\n');
assert.match(incrementalLabels, /\bdiffsliceIncrementalProbe\b/);
assert.doesNotMatch(incrementalLabels, /\bdiffsliceUnstagedProbe\b|\bdiffsliceUntrackedProbe\b/);
const diagnostics = JSON.parse(await readFile(incrementalReady.graphifyTimingsPath, 'utf8'));
assert.ok(diagnostics.stages.clusterMs > 0, 'Topology-changing update must run native clustering.');
await writeFile(path.join(output, 'incremental-report.json'), JSON.stringify({ incrementalMs, ready: incrementalReady, diagnostics }, null, 2));
await cli('hook', 'uninstall'); assert.equal(JSON.parse((await cli('hook', 'status')).stdout).installed, false);
const report = { source, isolatedRepo: repo, setupMs, commitMs, incrementalMs, warmMs, coldTimings: ready.timings, incrementalTimings: incrementalReady.timings, graphifyVersion: installed.hook.version, sql: installed.hook.sql, graphNodes: graph.nodes.length, graphEdges: (graph.links ?? graph.edges ?? []).length, stagedTree: tree, graphPath: ready.graphPath, cacheFiles: ready.files, stagedOnlyVerified: true, workingFilePreserved: true, privateRuntimeProvisioned: true, uninstallVerified: true, graphifyPlusDiffsliceMs: ready.elapsedMs };
await writeFile(path.join(output, 'report.json'), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
console.log(`Verified report: ${path.join(output, 'report.json')}`);
